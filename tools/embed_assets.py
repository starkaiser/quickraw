#!/usr/bin/env python3
"""Regenerate src/platform/qr_assets.c: the UI fonts and the window icon,
compiled into the program so a release is a single self-contained file.

    python3 tools/embed_assets.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = [  # (id, C symbol, file)
    (1, "font_regular", ROOT / "assets/fonts/Inter-Regular.ttf"),
    (2, "font_semibold", ROOT / "assets/fonts/Inter-SemiBold.ttf"),
    (3, "window_icon", ROOT / "packaging/icons/quickraw-64.png"),
]

def c_array(name, data):
    rows = []
    for i in range(0, len(data), 20):
        rows.append("    " + ",".join(str(b) for b in data[i:i + 20]))
    return f"static const unsigned char {name}[{len(data)}] = {{\n" + ",\n".join(rows) + "\n};\n"

def main():
    out = ["/* Generated by tools/embed_assets.py - do not edit. */",
           "/* Inter fonts: SIL Open Font License 1.1, see assets/fonts/LICENSE-Inter.txt */",
           "#include <stddef.h>", ""]
    for _, name, path in ASSETS:
        out.append(c_array(name, path.read_bytes()))
    out.append("/** Embedded file by id (1 regular font, 2 semibold font, 3 window icon PNG). */")
    out.append("const unsigned char *qr_asset(int id, int *size)\n{\n    switch (id) {")
    for ident, name, _ in ASSETS:
        out.append(f"    case {ident}: *size = (int)sizeof {name}; return {name};")
    out.append("    default: *size = 0; return NULL;\n    }\n}\n")
    target = ROOT / "src/platform/qr_assets.c"
    target.write_text("\n".join(out))
    print(f"wrote {target} ({target.stat().st_size} bytes)")

if __name__ == "__main__":
    main()
